// Explicit local input only. No download/install-time generation.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const [input, output, ...extra] = process.argv.slice(2);
if (!input || !output || extra.length) throw new Error("Usage: node scripts/generate-case-folding.mjs <local CaseFolding-17.0.0.txt> <output.ts>");
const bytes = await readFile(input);
const expected = "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183";
if (createHash("sha256").update(bytes).digest("hex") !== expected) throw new Error("Expected the approved Unicode 17.0.0 CaseFolding data (SHA-256 mismatch).");
const lines = bytes.toString("utf8").split(/\r?\n/);
const entries = [];
for (const line of lines) {
  const fields = line.split("#")[0].split(";").map((field) => field.trim());
  if (fields[1] !== "C" && fields[1] !== "F") continue;
  const code = Number.parseInt(fields[0], 16);
  const mapping = fields[2].split(/\s+/).map((value) => `\\u{${Number.parseInt(value, 16).toString(16)}}`).join("");
  entries.push(`  [0x${code.toString(16)}, "${mapping}"],`);
}
if (entries.length !== 1585) throw new Error("Unexpected C/F mapping count.");
const header = lines.slice(0, 5).map((line) => `// ${line.replace(/^# ?/, "")}`).join("\n");
await writeFile(output, `// Generated by scripts/generate-case-folding.mjs; do not edit.\n${header}\n// Unicode License V3: see LICENSE.unicode.\n// Source SHA-256: ${expected}\n// DEFAULT FULL case folding: C/F only, not S/T.\nexport const unicode17CaseFolding: ReadonlyMap<number, string> = new Map([\n${entries.join("\n")}\n]);\n`);
console.log(`Generated ${entries.length} Unicode 17.0.0 C/F mappings.`);
